
import React from 'react';
import Modal from '../../ui/Modal';
import Button from '../../ui/Button';
import { EconomicZoneStub, EconomicZoneType, GameLocation } from '../../../types';
import * as GameTemplates from '../../../templates';

interface EconomicZoneModalProps {
  isOpen: boolean;
  onClose: () => void;
  zones: EconomicZoneStub[];
  subLocations: GameLocation[];
  onEnterStub: (zone: EconomicZoneStub) => void;
  onEnterSubLocation: (loc: GameLocation) => void;
  isLoading: boolean;
  disabled: boolean;
}

const EconomicZoneModal: React.FC<EconomicZoneModalProps> = ({
  isOpen,
  onClose,
  zones,
  subLocations,
  onEnterStub,
  onEnterSubLocation,
  isLoading,
  disabled
}) => {
  const getIcon = (type: string) => {
    switch (type) {
      case EconomicZoneType.BLACKSMITH: return '⚔️';
      case EconomicZoneType.APOTHECARY: return '⚗️';
      case EconomicZoneType.TAVERN: return '🍺';
      case EconomicZoneType.MARKET: return '🛍️';
      case EconomicZoneType.FACTION_STORE: return '🏰';
      case EconomicZoneType.GENERAL_STORE: return '📦';
      case EconomicZoneType.AUCTION: return '⚖️';
      case EconomicZoneType.SLAVE_MARKET: return '⛓️';
      case GameTemplates.EconomyLocationType.MARKETPLACE: return '🛍️';
      case GameTemplates.EconomyLocationType.SHOPPING_CENTER: return '🏰';
      case GameTemplates.EconomyLocationType.AUCTION_HOUSE: return '⚖️';
      case GameTemplates.EconomyLocationType.SLAVE_MARKET: return '⛓️';
      case GameTemplates.EconomyLocationType.SLAVE_AUCTION: return '🔨';
      default: return '🏬';
    }
  };

  const hasContent = zones.length > 0 || subLocations.length > 0;

  return (
    <Modal isOpen={isOpen} onClose={onClose} title="CHỌN KHU VỰC GIAO DỊCH">
      <div className="">
        {!hasContent ? (
          <div className="text-center py-8 text-gray-500 italic">
            Khu vực này hiện chưa có cơ sở kinh doanh nào rõ rệt.
          </div>
        ) : (
          <div className="flex flex-col gap-4">
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 overflow-y-auto max-h-[60vh] p-1 custom-scrollbar">
              {/* Render Stubs (Generated by AI contextually) */}
              {zones.map((zone) => (
                <Button
                  key={zone.id}
                  variant="outline"
                  className="flex flex-col items-center justify-center p-3 h-28 text-center gap-2 border-gray-700 hover:border-amber-500/50 hover:bg-amber-900/10 group transition-all"
                  onClick={() => {
                    onEnterStub(zone);
                    onClose();
                  }}
                  disabled={disabled || isLoading}
                  title={zone.description}
                >
                  <span className="text-3xl group-hover:scale-110 transition-transform">{getIcon(zone.type)}</span>
                  <span className="text-xs font-bold text-gray-300 group-hover:text-amber-300 line-clamp-2 leading-tight">{zone.name}</span>
                </Button>
              ))}

              {/* Render SubLocations (Static/Explicit locations) */}
              {subLocations.map((loc) => (
                <Button
                  key={loc.id}
                  variant="outline"
                  className="flex flex-col items-center justify-center p-3 h-28 text-center gap-2 border-amber-600/30 hover:border-amber-500 hover:bg-amber-900/20 group transition-all"
                  onClick={() => {
                    onEnterSubLocation(loc);
                    onClose();
                  }}
                  disabled={disabled || isLoading}
                >
                  <span className="text-3xl group-hover:scale-110 transition-transform">{getIcon(loc.locationType as string)}</span>
                  <span className="text-xs font-bold text-amber-200 group-hover:text-amber-100 line-clamp-2 leading-tight">{loc.name}</span>
                </Button>
              ))}
            </div>
            
            <p className="text-[10px] text-gray-500 text-center italic px-2">
              Bấm vào biểu tượng để di chuyển đến khu vực tương ứng.
            </p>
          </div>
        )}
      </div>
    </Modal>
  );
};

export default EconomicZoneModal;
